// 在基础图末尾插入一个 ImageScale 节点，把 VAEDecode 输出的图片放大后再保存。
function withImageScale(base: Record<string, unknown>): Record<string, unknown> {
  const g = JSON.parse(JSON.stringify(base)) as {
    last_node_id: number;
    last_link_id: number;
    nodes: any[];
    links: any[];
  };
  const decode = g.nodes.find((n) => n.type === "VAEDecode");
  const save = g.nodes.find((n) => n.type === "SaveImage");
  const decodeOut = decode.outputs.find((o: any) => o.type === "IMAGE");
  const saveIn = save.inputs.find((i: any) => i.type === "IMAGE");
  const oldLinkId = decodeOut.links[0] as number;

  const scaleId = g.last_node_id + 1;
  const outLinkId = g.last_link_id + 1;

  // 原 VAEDecode → SaveImage 的 link 改为 VAEDecode → ImageScale
  const oldLink = g.links.find((l) => l[0] === oldLinkId);
  oldLink[3] = scaleId;
  oldLink[4] = 0;
  oldLink[5] = "IMAGE";

  // SaveImage 改从 ImageScale 取图
  saveIn.link = outLinkId;

  g.nodes.push({
    id: scaleId,
    type: "ImageScale",
    pos: [save.pos[0], save.pos[1] - 60],
    size: [210, 82],
    flags: {},
    order: save.order,
    mode: 0,
    inputs: [{ name: "image", type: "IMAGE", link: oldLinkId }],
    outputs: [{ name: "IMAGE", type: "IMAGE", links: [outLinkId], slot_index: 0 }],
    properties: { "Node name for S&R": "ImageScale" },
    widgets_values: ["bilinear", 1024, 1024, "disabled"],
  });

  g.links.push([outLinkId, scaleId, 0, save.id, 0, "IMAGE"]);

  return {
    last_node_id: scaleId,
    last_link_id: outLinkId,
    nodes: g.nodes,
    links: g.links,
    groups: [],
    config: {},
    extra: {},
    version: 0.4,
  };
}

// 修改 KSampler 的 denoise 强度（最后一个 widget），用于“修复/重绘”类工作流。
function withDenoise(base: Record<string, unknown>, denoise: number): Record<string, unknown> {
  const g = JSON.parse(JSON.stringify(base)) as { nodes: any[] };
  const sampler = g.nodes.find((n) => n.type === "KSampler");
  sampler.widgets_values[sampler.widgets_values.length - 1] = denoise;
  return g;
}

