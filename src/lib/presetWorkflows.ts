import type { LocalizedText } from "./i18n";

export type WorkflowDependencyKind = "model" | "node" | "manual";

export type WorkflowTag = "free" | "featured" | "hot";

export interface WorkflowDependency {
  kind: WorkflowDependencyKind;
  name: string;
  label: LocalizedText;
  git_url?: string;
}

export interface PresetWorkflow {
  id: string;
  name: LocalizedText;
  fileName: string;
  description: LocalizedText;
  category: string;
  tags: WorkflowTag[];
  publishedAt: string;
  likes: number;
  downloads: number;
  dependencies: WorkflowDependency[];
  graph: Record<string, unknown>;
  /** 工作流内用到中文提示词编码节点，安装/修复时需自动部署翻译节点 */
  needsTranslate?: boolean;
  /** 工作流内用到本地大模型节点（剧本/角色/翻译），安装/修复时需自动部署同一节点包 */
  needsLlm?: boolean;
  /** 工作流内用到配音（TTS）节点，安装/修复时需自动部署同一节点包 */
  needsTts?: boolean;
  /** 运行所需的最低显存（GB），用于按用户 GPU 显存标注是否可运行 */
  minVramGb?: number;
  /** 推荐显卡级别（型号 + 显存），用于“无法运行”提示里告诉用户该换什么卡 */
  gpuHint?: LocalizedText;
}

